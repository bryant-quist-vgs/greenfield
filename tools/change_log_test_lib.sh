g() { git -c commit.gpgsign=false -c core.hooksPath=/dev/null -C "$repo" "$@"; }
commit_all() { g add -A && g commit -q -m "$1"; }
head_of() { g rev-parse "$1"; }

passed=0 failed=0
ok() { passed=$((passed + 1)); }
fail() {
  failed=$((failed + 1))
  printf 'FAIL: %s\n' "$1"
  [ -n "${2:-}" ] && printf '%s\n' "$2" | sed 's/^/    /'
}
# is <label> <command...>: the command succeeds. isnt: it fails.
is() { if "${@:2}" >/dev/null 2>&1; then ok; else fail "$1" "${output:-}"; fi; }
isnt() { if "${@:2}" >/dev/null 2>&1; then fail "$1" "${output:-}"; else ok; fi; }

