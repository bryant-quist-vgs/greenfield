# entry <name> <title> [<tags>] [<file name>]: a valid entry, written by hand so that the
# form is stated here and not taken from the tool.
entry() {
  mkdir -p "$repo/$DIR"
  cat >"$repo/$DIR/${4:-$1.md}" <<EOF
---
id: change-$1
title: "$2"
is_source_of_truth: true
derives_from: []
status: current
date: ${1:0:10}
tags: [${3:-feature}]
---

# $2

## What changed

The gate checks the change log.

## Why

A change that is not recorded cannot be found again.
EOF
}

# new_repo <slug>: a repository with one commit that holds a file, an ignore rule for
# *.log, the tag file with no rows, and the list for no entries. It has no remote.
repo=""
new_repo() {
  repo="$work/$1"
  mkdir -p "$repo/docs"
  g init -q && g symbolic-ref HEAD refs/heads/main
  printf 'one\n' >"$repo/f.txt"
  printf '*.log\n/docs/change_log.md.tmp.*\n' >"$repo/.gitignore"
  tags_file
  { empty_log && printf 'No entries yet.\n'; } >"$repo/$LOG"
  commit_all seed
}
# valid <slug>: new_repo with the entry E1 and the list rendered, not committed.
valid() {
  new_repo "$1"
  entry "$N1" "First change"
  run render
}

# pair <slug>: an upstream repository and a clone of it. $repo is the clone, whose
# origin/HEAD names origin/main; $up_repo is the upstream.
up_repo=""
pair() {
  new_repo "$1.up"
  up_repo=$repo
  git clone -q "$up_repo" "$work/$1"
  repo="$work/$1"
}
# upstream <command...>: run the command in the upstream repository, commit there, and
# fetch into the clone. The tests fetch; the tool never does.
upstream() {
  local clone=$repo
  repo=$up_repo
  (cd "$repo" && "$@") && commit_all "upstream change"
  repo=$clone
  g fetch -q origin
}
# ours <command...>: run the command in $repo and commit there.
ours() { (cd "$repo" && "$@") && commit_all "our change"; }
# recorded <name> <title>: an entry and the list rendered with it, in $repo.
recorded() {
  entry "$1" "$2"
  run render
}
put() { printf '%s\n' "$2" >"$1"; }  # put <file> <line>

# edit <file> <sed expression>
edit() { sed "$2" "$repo/$1" >"$repo/$1.tmp" && mv "$repo/$1.tmp" "$repo/$1"; }

# Stand-ins on PATH, in front of the real programs. Every run goes through them.
#   git  writes each command line it is given to $SHIM_LOG. It fails the question that
#        has the argument $ASK (or answers it with $SAY, in which \0 is a NUL); with
#        $NTH, only the NTH such question of the run.
#   awk  fails when $AWK_MODE is fail, prints nothing when it is silent, prints a line
#        no parser prints when it is garbage, and a tag that is none when it is badtag;
#        with $AWK_FOR, only when its arguments hold that text (the name of a program).
#   mv   when $MV_MODE is term, sends the script that called it the signal TERM and
#        moves nothing.
mkdir "$work/shim"
printf '%s\n' '#!/bin/sh' 'printf "%s\n" "$*" >>"${SHIM_LOG:-/dev/null}"' 'for a in "$@"; do' \
  '  [ "$a" = "${ASK:-}" ] || continue' '  if [ -n "${NTH:-}" ]; then' \
  '    n=$(($(cat "$SHIM_N" 2>/dev/null || echo 0) + 1))' '    echo "$n" >"$SHIM_N"' \
  '    [ "$n" -eq "$NTH" ] || break' '  fi' \
  '  [ -z "${SAY:-}" ] || { printf "%b\n" "$SAY"; exit 0; }' \
  '  exit 3' 'done' "exec '$(command -v git)' \"\$@\"" >"$work/shim/git"
printf '%s\n' '#!/bin/sh' 'case "$*" in' '  *"${AWK_FOR:-}"*)' '    case "${AWK_MODE:-}" in' \
  '      fail) exit 1 ;;' '      silent) exit 0 ;;' \
  '      garbage) printf "X\tnot a line of the parser\nE\n"; exit 0 ;;' \
  '      badtag) printf "G\tNot A Tag\nE\n"; exit 0 ;;' '    esac ;;' 'esac' \
  "exec '$(command -v awk)' \"\$@\"" >"$work/shim/awk"
printf '%s\n' '#!/bin/sh' 'if [ "${MV_MODE:-}" = term ]; then kill -TERM "$PPID"; exit 1; fi' \
  "exec '$(command -v mv)' \"\$@\"" >"$work/shim/mv"
chmod +x "$work/shim/git" "$work/shim/awk" "$work/shim/mv"
shim_log="$work/git.log"
: >"$shim_log"

output="" status=0
# run <verb and options...>: the tool on $repo. with <NAME=value>... -- <verb...>: the
# same, with those variables added to the environment.
run() { with -- "$@"; }
with() {
  local vars=""
  while [ "$1" != -- ]; do
    vars="$vars $1"
    shift
  done
  shift
  rm -f "$work/shim.n"
  # shellcheck disable=SC2086 # the variables are split on purpose
  output=$(env PATH="$work/shim:$PATH" SHIM_LOG="$shim_log" SHIM_N="$work/shim.n" $vars bash "$tool" --repo "$repo" "$@" 2>&1 </dev/null)
  status=$?
}
# exits <label> <code>: the last run exited with that code.
exits() { if [ "$status" -eq "$2" ]; then ok; else fail "$1: expected exit $2, got $status" "$output"; fi; }
# says <label> <regex>: the last run printed a line that matches. silent: it did not.
says() { if printf '%s\n' "$output" | grep -Eq -- "$2"; then ok; else fail "$1: no line matches '$2'" "$output"; fi; }
silent() { if printf '%s\n' "$output" | grep -Eq -- "$2"; then fail "$1: a line matches '$2'" "$output"; else ok; fi; }
# clean <label> <verb...>: the run exits 0.
clean() {
  local label=$1
  shift
  run "$@"
  exits "$label" 0
}
# rule <label> <CLnn> <regex> [<verb...>]: the run (check, unless given) exits 1 with a
# line that cites the rule and matches.
rule() {
  local label=$1 id=$2 regex=$3
  shift 3
  [ $# -gt 0 ] || set -- check
  run "$@"
  if [ "$status" -ne 1 ]; then
    fail "$label: expected exit 1, got $status" "$output"
  elif ! printf '%s\n' "$output" | grep -E "^[^:]+:[0-9]+: $id " | grep -Eq -- "$regex"; then
    fail "$label: expected a $id violation matching '$regex'" "$output"
  else
    ok
  fi
}
# defect <slug> <rule> <file> <sed expression> <what> <regex>: plant one defect in a
# valid repository and require that rule to be reported.
defect() {
  valid "$1"
  edit "$3" "$4"
  rule "$2 $5" "$2" "$6"
}
# asked <verb> <argument that fails> [<answer in its place>]: a Git question that fails,
# or that is answered with something else, is exit 2.
asked() {
  with ASK="$2" SAY="${3:-}" -- "$1"
  exits "git fails the question $2 ($1)" 2
}

# everything: every file of $repo, the Git directory included, with its mode, size,
# time, and checksum. files: the files of the working tree, each with its checksum, and
# its links, each with its target. state: what a merge would change: the working tree,
# the index, HEAD, and whether a merge is in progress.
everything() { (cd "$repo" && find . -exec ls -ld {} + && find . -type f -exec cksum {} + | sort); }
files() {
  (cd "$repo" && {
    find . -name .git -prune -o -type f -exec cksum {} +
    find . -name .git -prune -o -type l -exec sh -c 'for l; do printf "0 0 %s -> %s\n" "$l" "$(readlink "$l")"; done' sh {} +
  } | sort -k 3)
}
state() {
  files
  g ls-files -s
  g rev-parse HEAD
  g rev-parse -q --verify MERGE_HEAD || echo "no merge in progress"
}
# writes_nothing <label> <verb...>: the run changes no file, the Git directory included.
writes_nothing() {
  local label=$1
  shift
  everything >"$work/before.txt"
  run "$@"
  everything >"$work/after.txt"
  if cmp -s "$work/before.txt" "$work/after.txt"; then ok
  else fail "$label: the run changed the repository" "$(diff "$work/before.txt" "$work/after.txt")"; fi
}
# unchanged <label> <state before>: the working tree, the index, and HEAD are as before.
unchanged() { if [ "$2" = "$(state)" ]; then ok; else fail "$1: the tree, the index, or HEAD changed" "$output"; fi; }
# changed_files <label> <files before> <path>...: the files of the working tree that
# were added, removed, or changed since then are exactly those paths.
changed_files() {
  local label=$1 before=$2 now names expected=""
  shift 2
  now=$(files)
  names=$( { printf '%s\n' "$before" | grep -vxF -e "$now"; printf '%s\n' "$now" | grep -vxF -e "$before"; } |
    sed 's/^[0-9]* [0-9]* \.\///' | sort -u | tr '\n' ' ')
  [ $# -eq 0 ] || expected=$(printf '%s\n' "$@" | sort | tr '\n' ' ')
  if [ "$names" = "$expected" ]; then ok
  else fail "$label: the files that changed are: $names" "$output"; fi
}
# only_git_commands <label> <regex of the commands allowed>: every command the stand-in
# git was given carries the options that pin Git and is one of those commands; only
# merge and add are run without --no-optional-locks. A subcommand that has a form that
# writes is allowed in its reading form only: $ASKS_CHECK is what check may ask, and
# $ASKS_SYNC what sync may.
ASKS_CHECK='rev-parse|symbolic-ref -q (HEAD|refs/remotes/origin/HEAD)$|for-each-ref --count=1 --format=%\(refname\) [^ ]+$|config --get-regexp [^ ]+$|ls-files|merge-base --is-ancestor|diff --cached|status --porcelain=v1'
ASKS_SYNC="$ASKS_CHECK|merge-tree --write-tree|diff-tree -r -z|cat-file blob"
only_git_commands() {
  local pins='-c core\.fsmonitor=false -c core\.hooksPath=/dev/null -c maintenance\.auto=false -c gc\.auto=0 -C [^ ]+'
  local bad
  bad=$(grep -Ev -e "^--no-optional-locks $pins (-c core\\.quotePath=true )?($2)( |\$)" \
    -e "^$pins (-c rerere\\.enabled=false -c submodule\\.recurse=false merge --no-commit --no-edit --no-autostash --no-stat --no-squash --ff -s ort [0-9a-f]{40}|add -- $LOG)\$" "$shim_log")
  if [ -z "$bad" ] && [ -s "$shim_log" ]; then ok; else fail "$1: a Git command outside the list" "$bad"; fi
}
